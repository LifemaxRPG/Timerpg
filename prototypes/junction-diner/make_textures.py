def text(im,s,x,y,col,scale=1):
 d=ImageDraw.Draw(im)
 for ch in s.upper():
  for j,row in enumerate(FONT.get(ch,['00000']*7)):
   for k,v in enumerate(row):
    if v=='1':d.rectangle((x+k*scale,y+j*scale,x+(k+1)*scale-1,y+(j+1)*scale-1),fill=col)
  x+=6*scale
