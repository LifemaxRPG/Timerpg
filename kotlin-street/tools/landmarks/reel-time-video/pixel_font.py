def measure_text(text, font="5x7", spacing=1, scale=1):
    """Returns exact (width_art_px, height_art_px) for strict fit assertions."""
    cw, ch = (5, 7) if font == "5x7" else (3, 5)
    n = len(text)
    if n == 0:
        return 0, ch * scale
    w = n * cw * scale + (n - 1) * spacing * scale
    return w, ch * scale
