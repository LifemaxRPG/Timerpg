#!/usr/bin/env python3
"""
The pack's own store buildings (9_Shopping_Center_and_Markets: Market_Small x12 'STORE', Market_Medium x12 and Market_Big x6
'MARKET', Mall_1; 4_Generic_Building: Hardware_Store) packed for the store builder: each sprite as one deflated, palette-
indexed picture in a generated Kotlin file (PackStoreData.kt), with the rows that split it into the roof seen from above
and the front elevation, and where its sign plate is. The 32 px art, never resampled.

  pack_stores.py --root exteriors=DIR --kotlin shared/src/filament/kotlin/scene3d/PackStoreData.kt
"""
import argparse, base64, os, zlib
from PIL import Image

M = '9_Shopping_Center_and_Markets_Singles_32x32/ME_Singles_Shopping_Center_and_Markets_32x32_'
G = '4_Generic_Building_Singles_32x32/ME_Singles_Generic_Building_32x32_'
PLATE = {'small': (20, 158, 76, 178), 'medium': (66, 160, 158, 196), 'big1': (66, 254, 158, 292), 'big2': (66, 246, 158, 284)}

def designs():
    d = []
    for i in range(1, 13): d.append((f'store_s_{i}', M + f'Market_Small_{i}.png', 'small'))
    for i in range(1, 13): d.append((f'market_m_{i}', M + f'Market_Medium_{i}.png', 'medium'))
    for i in range(1, 7): d.append((f'market_b_{i}', M + f'Market_Big_{i}.png', 'big1' if i % 2 else 'big2'))
    d.append(('hardware', G + 'Hardware_Store.png', 'hardware'))
    d.append(('mall', M + 'Mall_1.png', 'mall'))
    return d

def rows_of(im, fam):
    w, h = im.size
    first = next(y for y in range(h) if any(im.getpixel((x, y))[3] for x in range(w)))
    last = max(y for y in range(h) if any(im.getpixel((x, y))[3] for x in range(w)))
    def dark(y):
        px = [im.getpixel((x, y)) for x in range(w)]; op = sum(1 for p in px if p[3])
        return op and sum(1 for p in px if p[3] and p[0] < 0x50 and p[1] < 0x50) / op > .55
    if fam in ('hardware',): return first, 180, last + 1
    if fam == 'mall': return first, 206, last + 1
    cor = next(y for y in range(100, h - 3) if all(dark(y + k) for k in range(4)))
    return first, cor - (22 if fam.startswith('big') else 6), last + 1

def fix_mall(im):
    """The poster with a fruit and a made-up word in its corner: only the fruit, mirrored across (no brand-like word on it)."""
    src = im.crop((60, 322, 124, 362)); im.paste(src.transpose(Image.FLIP_LEFT_RIGHT), (124, 322)); im.paste(src, (60, 322))
    im.paste(src.crop((0, 0, 60, 40)), (124, 322)) if False else None
    return im

def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--root', action='append', default=[]); ap.add_argument('--kotlin', required=True)
    a = ap.parse_args(); roots = dict(r.split('=', 1) for r in a.root)
    out = ['package com.lifemax.rpg.feature.habits.presentation.scene3d', '',
           '// GENERATED by tools/swatches/pack_stores.py: do not edit. The pack\'s store sprites (32 px art), one deflated indexed picture each.',
           'internal object PackStoreData {',
           '    /** id, size, first roof row, roof ends (the front elevation starts here), last row + 1, sign plate x0 y0 x1 y1 (or 0s), the picture */',
           '    class Sprite(val id: String, val w: Int, val h: Int, val top: Int, val roofEnd: Int, val bottom: Int, val plate: IntArray, val data: List<String>)',
           '    val ALL: List<Sprite> = listOf(']
    for id_, f, fam in designs():
        im = Image.open(os.path.join(roots['exteriors'], f)).convert('RGBA')
        if fam == 'mall': im = fix_mall(im)
        top, roofEnd, bottom = rows_of(im, fam)
        pal = {}; idx = bytearray()
        for p in im.getdata():
            p = (0, 0, 0, 0) if p[3] < 128 else p
            idx.append(pal.setdefault(p, len(pal)))
        assert len(pal) < 256, id_
        raw = bytes([len(pal)]) + b''.join(bytes(c) for c in pal) + bytes(idx)
        b64 = base64.b64encode(zlib.compress(raw, 9)).decode()
        chunks = [b64[i:i + 30000] for i in range(0, len(b64), 30000)]
        plate = PLATE.get(fam, (0, 0, 0, 0))
        out.append('        Sprite("%s", %d, %d, %d, %d, %d, intArrayOf(%s), listOf(%s)),' % (id_, im.width, im.height, top, roofEnd, bottom, ', '.join(map(str, plate)), ', '.join('"%s"' % c for c in chunks)))
        print(id_, im.size, top, roofEnd, bottom, len(b64))
    out += ['    )', '}', '']
    open(a.kotlin, 'w').write('\n'.join(out))

if __name__ == '__main__': main()
