#!/usr/bin/env python3
"""Cuts the railroad's pieces out of LimeZu's Modern Exteriors pack (20_Subway_and_Train_Station, 32 px art) for the
Filament town's rail kit (shared/.../scene3d/RailKit.kt): the track tiles (wooden and concrete ties, a broken stretch)
and the trains' cars (each one picture: the roof seen from above over the side). Each piece is packed like
pack_stores.py packs the stores: one deflated, palette-indexed picture, base64, into RailPackData.kt.

Usage: python3 pack_rail.py <dir of the pack's 32x32 singles> <out RailPackData.kt>
(the pack: kotlin-street/packs/join.sh into a scratch folder, unzip the singles there; never into the repo)
"""
import base64, os, sys, zlib
from PIL import Image

PIECES = [
    # id, the single's name, crop (x0, y0, x1, y1) or None
    ('track_wood', 'Brown_Rail_Modular_Horizontal', None),
    ('track_concrete', 'Grey_Rail_Modular_Horizontal', None),
    ('track_broken', 'Brown_Rail_Broken_Horizontal', None),
    ('car_orange_end', 'Exterior_Train_Orange_Left', None),
    ('car_orange_mid', 'Exterior_Train_Orange_Middle', None),
    ('car_green_end', 'Exterior_Train_Green_Left', None),
    ('car_green_mid', 'Exterior_Train_Green_Middle', None),
    ('car_grey_mid', 'Exterior_Train_Grey_Middle', None),
    ('car_blue_mid', 'Exterior_Train_Blue_Middle', None),
    ('lamp_on', 'Led_Light_On', None),
]

def find(d, name):
    for f in os.listdir(d):
        if f.endswith('_' + name + '.png'): return os.path.join(d, f)
    raise SystemExit('missing ' + name)

def pack(im):
    im = im.convert('RGBA')
    pal, idx = [], bytearray()
    for p in im.getdata():
        if p[3] < 128: p = (0, 0, 0, 0)
        if p not in pal: pal.append(p)
        idx.append(pal.index(p))
    assert len(pal) <= 256
    raw = bytes([len(pal) % 256]) + b''.join(bytes(p) for p in pal) + bytes(idx)
    return base64.b64encode(zlib.compress(raw, 9)).decode()

def main():
    src, out = sys.argv[1], sys.argv[2]
    lines = ['package com.lifemax.rpg.feature.habits.presentation.scene3d', '',
             '// GENERATED by tools/swatches/pack_rail.py: do not edit. The railroad\'s pieces from the pack (32 px art), one deflated indexed picture each.',
             'internal object RailPackData {', '    class Piece(val id: String, val w: Int, val h: Int, val data: List<String>)', '    val ALL: List<Piece> = listOf(']
    for pid, name, crop in PIECES:
        im = Image.open(find(src, name))
        if crop: im = im.crop(crop)
        b = pack(im)
        chunks = [b[i:i + 900] for i in range(0, len(b), 900)]
        lines.append('        Piece("%s", %d, %d, listOf(%s)),' % (pid, im.width, im.height, ', '.join('"%s"' % c for c in chunks)))
    lines += ['    )', '}', '']
    open(out, 'w').write('\n'.join(lines))

main()
