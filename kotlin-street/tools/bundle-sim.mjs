#!/usr/bin/env node
// Bundles the game's TypeScript simulation for the phone (docs/LOOP.md, "The JavaScript bridge"): src/loop/bridge.ts
// and everything it imports (src/crime, src/plan, src/police, src/sim...) into one script,
// kotlin-street/app/src/main/assets/sim/sim.js, an IIFE that sets the API on globalThis. SimJs.kt runs it in
// QuickJS-ng (app/src/main/cpp/simjs) on the phone and the desktop.
//
// node kotlin-street/tools/bundle-sim.mjs [--out FILE] [--minify]
//
// platform "neutral": no Node built-ins resolve, so an import of one (node:fs, perf_hooks...) fails the bundle; the
// output is then also checked for Node globals (require, process, Buffer, __dirname) that a dependency might use.
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import fs from 'node:fs';

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, '../..');
const require = createRequire(path.join(repo, 'package.json'));
const esbuild = require('esbuild');

const args = process.argv.slice(2);
const outArg = args.indexOf('--out');
const out = outArg >= 0 ? path.resolve(args[outArg + 1]) : path.join(repo, 'kotlin-street/app/src/main/assets/sim/sim.js');
const entry = path.join(repo, 'src/loop/bridge.ts');

const result = await esbuild.build({
  entryPoints: [entry],
  outfile: out,
  bundle: true,
  format: 'iife',
  platform: 'neutral',
  // QuickJS-ng runs ES2023; ES2022 keeps the output plain
  target: 'es2022',
  mainFields: ['module', 'main'],
  minify: args.includes('--minify'),
  legalComments: 'none',
  charset: 'utf8',
  metafile: true,
  logLevel: 'warning',
  banner: { js: '// Generated by kotlin-street/tools/bundle-sim.mjs from src/loop/bridge.ts. Do not edit.' },
});

const code = fs.readFileSync(out, 'utf8');
const nodeOnly = [/\brequire\s*\(/, /\bprocess\s*\./, /\bBuffer\s*\./, /\b__dirname\b/, /\b__filename\b/, /from\s+["']node:/];
const hits = nodeOnly.filter((re) => re.test(code));
if (hits.length > 0) {
  console.error(`bundle-sim: ${path.relative(repo, out)} uses Node APIs: ${hits.map(String).join(', ')}`);
  process.exit(1);
}
const inputs = Object.keys(result.metafile.inputs).length;
console.log(`bundle-sim: ${path.relative(repo, out)} (${(code.length / 1024).toFixed(1)} KiB from ${inputs} files), no Node APIs`);
