import org.junit.Assert.assertEquals
import org.junit.Assert.assertFalse
import org.junit.Assert.assertNotEquals
import org.junit.Assert.assertTrue
import org.junit.Test

/**
 * The scene's pre-rendered art (cloud sprites, tree sprites, the film grain) is generated by pure
 * Kotlin from seeds: the same pixels every time, alpha in range, feathered edges, every sprite
 * inside its size, the whole pool inside its memory budget, and the clouds hung clear of the "add a
 * floor" hint.
 */
class SpritesTest {
    private val clouds: List<CloudSprite> by lazy {
        CloudSprites.SPECS.indices.map { CloudSprites.generate(it) }
    }

    private fun layers(c: CloudSprite) = listOf(c.shade, c.mid, c.lit, c.under)

    @Test
    fun cloudSpritesAreTheSameEveryTime() {
        for (i in CloudSprites.SPECS.indices) {
            val a = clouds[i]
            val b = CloudSprites.generate(i)
            assertArrayEquals(a.shade, b.shade)
            assertArrayEquals(a.mid, b.mid)
            assertArrayEquals(a.lit, b.lit)
            assertArrayEquals(a.under, b.under)
        }
        // and they are all different clouds
        for (i in clouds.indices) for (j in i + 1 until clouds.size) {
            if (clouds[i].w == clouds[j].w && clouds[i].h == clouds[j].h)
                assertFalse(clouds[i].shade.contentEquals(clouds[j].shade))
        }
    }

    @Test
    fun cloudSpritesHaveSizesKindsAndTintableLayers() {
        assertEquals(8, clouds.size)
        for (k in CloudKind.entries) assertEquals(Ambient.CLOUD_VARIANTS, CloudSprites.of(k).size)
        for ((i, c) in clouds.withIndex()) {
            val spec = CloudSprites.SPECS[i]
            assertEquals(spec.w * spec.h, c.shade.size)
            assertEquals(spec.w / CloudSprites.PX_PER_DP, c.dpW, 0f)
            assertTrue(c.dpW in 60f..170f && c.dpH in 25f..100f)
            for (layer in layers(c)) {
                assertEquals(c.w * c.h, layer.size)
                // white at every alpha, so a tint can colour it
                assertTrue(layer.all { (it ushr 24) == 0 || (it and 0xFFFFFF) == 0xFFFFFF })
            }
            // the cloud is there: something dense, something lit
            assertTrue(
                c.shade.any { (it ushr 24) > (if (spec.kind == CloudKind.CIRRUS) 100 else 200) }
            )
            assertTrue(c.lit.any { (it ushr 24) > 80 } || spec.kind == CloudKind.CIRRUS)
            // the light is a part of the cloud, never more than the cloud
            for (p in c.shade.indices) {
                assertTrue((c.mid[p] ushr 24) <= (c.shade[p] ushr 24))
                assertTrue((c.lit[p] ushr 24) <= (c.shade[p] ushr 24))
            }
        }
    }

    @Test
    fun cloudEdgesAreFeatheredWithNoOutlineAndNothingTouchesTheBorder() {
        for (c in clouds) {
            val a = { x: Int, y: Int -> (c.shade[y * c.w + x] ushr 24) }
            for (x in 0 until c.w) {
                assertEquals(0, a(x, 0))
                assertEquals(0, a(x, c.h - 1))
            }
            for (y in 0 until c.h) {
                assertEquals(0, a(0, y))
                assertEquals(0, a(c.w - 1, y))
            }
            // no hard step: neighbouring pixels never jump from clear to solid (a drawn outline
            // would be 255)
            var steepest = 0
            for (y in 0 until c.h) for (x in 0 until c.w - 1) steepest =
                maxOf(steepest, abs(a(x, y) - a(x + 1, y)))
            for (y in 0 until c.h - 1) for (x in 0 until c.w) steepest =
                maxOf(steepest, abs(a(x, y) - a(x, y + 1)))
            assertTrue("steepest edge $steepest in ${c.w}x${c.h}", steepest < 170)
        }
    }

    @Test
    fun cloudShapesDifferByKind() {
        fun extent(c: CloudSprite): Pair<Int, Int> {
            var x0 = c.w
            var x1 = 0
            var y0 = c.h
            var y1 = 0
            for (y in 0 until c.h) for (x in 0 until c.w) if ((c.shade[y * c.w + x] ushr 24) > 40) {
                x0 = minOf(x0, x)
                x1 = maxOf(x1, x)
                y0 = minOf(y0, y)
                y1 = maxOf(y1, y)
            }
            return (x1 - x0) to (y1 - y0)
        }
        for ((i, c) in clouds.withIndex()) {
            val (w, h) = extent(c)
            when (CloudSprites.SPECS[i].kind) {
                // a streak is flat, a heap is tall
                CloudKind.STRATUS -> assertTrue(w > 3 * h)
                CloudKind.CIRRUS -> assertTrue(w > 2 * h)
                CloudKind.CUMULUS -> assertTrue(h * 10 > w * 4 && w > 100)
                CloudKind.PUFF -> assertTrue(w > 30)
            }
        }
    }

    @Test
    fun treeSpritesAreTheSameEveryTimeAndHaveThreeLooks() {
        for (v in 0 until Trees.VARIANTS) {
            val a = TreeSprites.generate(v)
            val b = TreeSprites.generate(v)
            assertEquals(TreeLook.entries.size, a.pixels.size)
            for (l in a.pixels.indices) {
                assertEquals(a.w * a.h, a.pixels[l].size)
                assertArrayEquals(a.pixels[l], b.pixels[l])
            }
            // the three looks are different pictures with the same silhouette
            assertFalse(a.pixels[0].contentEquals(a.pixels[2]))
            for (p in a.pixels[0].indices) assertEquals(
                a.pixels[0][p] ushr 24,
                a.pixels[2][p] ushr 24,
            )
        }
    }

    @Test
    fun treeSpritesFitTheirRoomStandOnTheFootAndAreLitFromTheLeft() {
        for (v in 0 until Trees.VARIANTS) {
            val s = TreeSprites.generate(v)
            val shape = Trees.shapes[v]
            // the picture is about the tree's size (in units) and nothing touches its border
            assertTrue(s.w / s.ppu >= shape.halfWidth * 2f)
            assertTrue(s.h / s.ppu >= shape.height)
            for (look in s.pixels) {
                for (x in 0 until s.w) assertEquals(0, look[x] ushr 24)
                for (y in 0 until s.h) {
                    assertEquals(0, look[y * s.w] ushr 24)
                    assertEquals(0, look[y * s.w + s.w - 1] ushr 24)
                }
            }
            // the trunk stands on the foot, with a soft shadow round it
            val foot = s.pixels[0][(s.footY.toInt() - 3) * s.w + s.footX.toInt()]
            assertTrue((foot ushr 24) > 220)
            assertTrue(s.pixels[0].count { (it ushr 24) in 10..120 } > 40)
            // day is brighter than night; the light side is brighter than the far side (leaves)
            fun lum(c: Int) =
                ((c shr 16) and 255) * .3f + ((c shr 8) and 255) * .59f + (c and 255) * .11f
            fun mean(look: IntArray, x0: Int, x1: Int): Float {
                var sum = 0f
                var n = 0
                for (y in 0 until (s.footY.toInt() - 8 * s.ppu.toInt())) for (x in x0 until x1) {
                    val c = look[y * s.w + x]
                    if ((c ushr 24) > 200) {
                        sum += lum(c)
                        n++
                    }
                }
                return if (n == 0) 0f else sum / n
            }
            val day = mean(s.pixels[0], 0, s.w)
            val night = mean(s.pixels[2], 0, s.w)
            assertTrue("day $day night $night", day > night * 1.6f)
            val left = mean(s.pixels[0], 0, s.w / 2)
            val right = mean(s.pixels[0], s.w / 2, s.w)
            assertTrue("left $left right $right", left > right)
        }
    }

    @Test
    fun theTreeVariantIsChosenBySeedAndAllAreReachable() {
        val seen = (0 until 400).map { Trees.variant(it) }.toSet()
        assertEquals((0 until Trees.VARIANTS).toSet(), seen)
        for (s in -20..20) assertEquals(Trees.variant(s), Trees.variant(s))
    }

    @Test
    fun theWholePoolFitsItsMemoryBudget() {
        val bytes = CloudSprites.bytes() + TreeSprites.bytes() + Grain.SIZE * Grain.SIZE * 4
        assertTrue("pool is $bytes bytes", bytes < 8 * 1024 * 1024)
        // clouds: four layers; trees: three looks
        assertEquals(clouds.sumOf { it.w * it.h * 16 }, CloudSprites.bytes())
    }

    @Test
    fun cloudsHangClearOfTheAddAFloorGhost() {
        val d = 2.6f
        val horizon = 900f
        val top = 260f
        for (ceiling in listOf(250f, 330f, 450f, 600f, 780f, 880f, 2000f)) {
            val room = CloudLayout.room(top, horizon, ceiling, d)
            assertTrue(room in 0f..1f)
            val floor = CloudLayout.floor(horizon, ceiling, d)
            for (lane in Ambient.CLOUD_LANES) {
                val base = CloudLayout.base(lane, top, horizon, ceiling, d)
                // a cloud's foot never goes below the ceiling less its margin (the ghost stands on
                // the roof)
                assertTrue(
                    "lane $lane ceiling $ceiling base $base floor $floor",
                    base <= maxOf(floor, top + 1f) + .001f,
                )
                assertTrue(base >= top - .001f)
            }
            // with no room the whole sky is faded out rather than squeezed onto the hint
            if (ceiling <= top + 14f * d) assertEquals(0f, room, 0f)
        }
        // lower lanes are lower, and a taller building lowers none of them below its roof
        val lanes = Ambient.CLOUD_LANES.map { CloudLayout.base(it, top, horizon, 600f, d) }
        assertTrue(lanes.zipWithNext().all { (a, b) -> a < b })
        assertNotEquals(
            CloudLayout.base(.3f, top, horizon, 600f, d),
            CloudLayout.base(.3f, top, horizon, 400f, d),
        )
    }

    @Test
    fun theFilmGrainIsFineAndCentred() {
        val a = Grain.pixels()
        val b = Grain.pixels()
        assertArrayEquals(a, b)
        assertEquals(Grain.SIZE * Grain.SIZE, a.size)
        // black and white specks of low alpha, balanced, so the grain neither lightens nor darkens
        var light = 0L
        var dark = 0L
        for (c in a) {
            assertTrue((c ushr 24) <= 255)
            if ((c and 0xFF) > 128) light += c ushr 24 else dark += c ushr 24
        }
        assertTrue(abs(light - dark) < (light + dark) / 10)
    }
}
